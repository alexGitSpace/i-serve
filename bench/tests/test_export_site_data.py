"""The site's data files are what bench/ produces -- and nothing else.

`site/data/` is generated by bench/export_site_data.py and committed, so the
page can be served as static files. Committed and generated is the pair that
drifts: a coefficient changes in roofline.py and the page keeps showing the old
one. This file holds the two equal, the way test_plot_predicted_vs_measured.py
holds the chart to its data, and checks the properties the JavaScript relies
on -- no Infinity, a .js twin that is the JSON bytes, a golden grid that reaches
every branch of what_if_point().

No dependency on pytest, which is not installed here -- plain functions, plain
asserts, and a runner at the bottom:

    python3 bench/tests/test_export_site_data.py
"""

# Two ways in, and both have to work. `pytest bench/` gets bench/ on the import
# path from tests/conftest.py; `python3 bench/tests/test_roofline.py` on a rented
# pod, where pytest is not installed, gets only this directory. The three lines
# below are what make the second one work, and they are here rather than in
# conftest.py for exactly that reason.
import pathlib as _pathlib
import sys as _sys

_sys.path.insert(0, str(_pathlib.Path(__file__).resolve().parent.parent))


import json
import re

import export_site_data as export
from predictions import INTERFERENCE_MODEL, MODELS
from roofline import ACCELERATORS

FILES = export.outputs()


def test_committed_site_data_is_what_the_export_produces():
    """Editing a coefficient without regenerating is the failure this catches."""
    stale = [name for name, text in FILES.items()
             if (export.SITE_DATA / name).read_text(encoding="utf-8") != text]
    assert not stale, (f"site/data is stale: {stale} -- run "
                       f"python3 bench/export_site_data.py")


def test_the_js_twins_are_the_json_bytes_behind_a_prefix():
    for name, global_name in (("model", "MODEL_DATA"), ("golden", "GOLDEN")):
        js = FILES[f"{name}.js"]
        prefix = f"window.{global_name} = "
        assert js.startswith(prefix) and js.endswith(";\n"), name
        assert js[len(prefix):-2] == FILES[f"{name}.json"].rstrip(), name
    twin = FILES["symptom-map.js"]
    assert twin.startswith("window.SYMPTOM_MAP = ")
    assert json.loads(twin[len("window.SYMPTOM_MAP = "):-2]) == \
        json.loads(export.SYMPTOM_MAP.read_text(encoding="utf-8"))


def test_export_is_deterministic():
    assert export.dumps(export.model_data()) == FILES["model.json"]
    assert export.dumps_rows(export.golden_grid()) == FILES["golden.json"]


def test_no_infinity_and_no_nan_reach_the_page():
    for name in ("model.json", "golden.json"):
        text = FILES[name]
        assert "Infinity" not in text and "NaN" not in text, name
        json.loads(text)


def test_every_number_the_page_needs_is_in_model_json():
    data = json.loads(FILES["model.json"])
    assert set(data["accelerators"]) == set(ACCELERATORS)
    for key, card in data["accelerators"].items():
        assert card["provenance"], key
        assert card["measured"] == card["provenance"].startswith("measured"), key
        assert card["hourly_rate"] > 0 and card["hourly_rate_provenance"], key
    assert set(data["interference"]) == {"l40s-run1", "l40s"}
    assert data["slo_classes"]["interactive"] == {"ttft_s": 0.3, "tpot_s": 0.05}
    assert data["slo_classes"]["batch"] == {"ttft_s": 3.0, "tpot_s": 0.2}
    assert data["constants"]["FLOPS_PER_MAC"] == 2
    assert data["defaults"]["model"] in data["models"]
    assert data["models"][data["defaults"]["model"]]["name"] == "Qwen3-8B"
    # Exactly one model may be drawn measured points over and lent the fit, and
    # the page reads which from here rather than carrying a copy of the fact.
    measured = [k for k, m in data["models"].items() if m["measured"]]
    assert measured == [data["measured"]["model"]] == ["qwen3-8b"], measured
    for key, m in data["models"].items():
        assert m["provenance"] and m["kv_bytes_per_token"] > 0, key
        assert m["served_by_this_stack"] == (key == data["defaults"]["model"]), key
    assert set(data["runs"]) == {"1", "2", "3", "4"}
    assert "generated_at" not in data and "sha" not in data, "byte-stability"


def test_measured_seat_crossings_are_the_ones_slo_md_quotes():
    """12.5 and 37.8 -- the two figures docs/SLO.md section 6 quotes on one row."""
    crossings = json.loads(FILES["model.json"])["measured"]["seat_crossings"]
    assert round(crossings["h0"], 1) == 12.5 and round(crossings["h80"], 1) == 37.8
    body = (export.ROOT / "docs/SLO.md").read_text(encoding="utf-8")
    rows = [line for line in body.splitlines()
            if "**12.5**" in line and "**37.8**" in line]
    assert len(rows) == 1, rows


def test_measured_sets_carry_their_geometry():
    """The page hides a run's points when the sliders leave the run's geometry;
    it can only do that if every set says what it was taken at.
    """
    measured = json.loads(FILES["model.json"])["measured"]
    for name in ("run1_decode", "run2_rates", "run3_seats", "run3_rates"):
        block = measured[name]
        for field in ("run", "mode", "accelerator", "prompt_tokens", "output_tokens",
                      "kv_dtype_bytes", "gpu_memory_utilization"):
            assert field in block, (name, field)
    assert [s["hit_rate"] for s in measured["run3_seats"]["series"]] == [0.0, 0.8]
    assert len(measured["run1_decode"]["levels"]) == 12
    assert len(measured["run2_rates"]["levels"]) == 8


def test_golden_covers_every_branch_of_the_point_function():
    rows = json.loads(FILES["golden.json"])
    assert len(rows) > 150, len(rows)
    expected = [r["expected"] for r in rows]
    assert any(e["error"] and e["seats"] is None for e in expected), "weights-do-not-fit edge"
    assert any(e["error"] and e["seats"] and e["seats"]["max_num_seqs"] == 0
               for e in expected), "zero-seat edge"
    assert any(e["seats"] and e["seats"]["bound_by"] == "capacity" for e in expected)
    assert any(e["seats"] and e["seats"]["bound_by"] == "latency" for e in expected)
    assert any(e["service"] is None and not e["error"] for e in expected), "no-fit card"
    assert any(e["service"] and e["service"]["bound_by"] == "capacity" for e in expected), \
        "a service seat count capped by the pool"
    assert any(e["service"] and e["service"]["note"] for e in expected), "the h > 0.5 note"
    # The crossing this repository measures at: the default point at 50 ms.
    assert any(r["inputs"]["accelerator"] == "l40s-run1" and r["inputs"]["prompt_tokens"] == 4000
               and r["inputs"]["tpot_target"] == 0.05 and r["inputs"]["kv_dtype_bytes"] == 2
               and r["expected"]["seats"]["max_num_seqs"] == 31 for r in rows)


def test_every_model_the_page_offers_is_held_to_python():
    """A third model in MODELS reaches the page by itself; its arithmetic must not.

    site/ui.js builds the model list from Object.keys(data.models), so adding a
    Model(...) and a line in MODELS puts it in front of a reader without anyone
    touching the page. Nothing in that path holds calc.js equal to roofline.py
    for the new model: the golden grid names its two models one at a time. This
    is the assertion that turns "add golden rows for it" from a thing to
    remember into a thing CI refuses to skip -- on every card, because eff_mem
    and mfu are where a port drifts, and on both KV dtypes.
    """
    rows = json.loads(FILES["golden.json"])
    seen = {}
    for row in rows:
        seen.setdefault(row["inputs"]["model"], set()).add(
            (row["inputs"]["accelerator"], row["inputs"]["kv_dtype_bytes"]))
    missing = sorted(set(MODELS) - set(seen))
    assert not missing, (f"models with no golden rows: {missing} -- add them to "
                         f"golden_grid() in bench/export_site_data.py")
    for key in MODELS:
        cards = {card for card, _ in seen[key]}
        assert cards == set(ACCELERATORS), \
            f"{key} is priced on {sorted(cards)}, not on every card in ACCELERATORS"
        assert {kv for _, kv in seen[key]} == {1, 2}, f"{key} on one KV dtype only"


def test_the_interference_fit_is_withheld_from_every_other_model():
    """"Not derivable" is a claim the grid has to carry, or the page invents one.

    The fit was measured decoding one model; lending it to a second architecture
    is the error predictions.py names in a comment and refuses in code. If no
    golden row ever asks a second model for a service answer, the refusal lives
    only in the JavaScript, where nothing checks it.
    """
    rows = json.loads(FILES["golden.json"])
    others = [r for r in rows
              if r["inputs"]["model"] != INTERFERENCE_MODEL
              and r["inputs"]["accelerator"].startswith("l40s")
              and not r["expected"]["error"]]
    assert others, "no golden row prices a second model on the card the fit belongs to"
    assert all(r["expected"]["service"] is None for r in others), \
        "a model the fit was not measured on came back with a service seat count"


def test_one_golden_row_per_line():
    """So a diff names the operating point that moved rather than a byte offset."""
    lines = FILES["golden.json"].splitlines()
    assert lines[0] == "[" and lines[-1] == "]"
    assert all(re.match(r'^\{"expected": ', line.rstrip(",")) for line in lines[1:-1])


